#!/usr/bin/env python3
"""C2 decision analysis: applies the pre-registered rule (charter §5 + Amendment A1).

Version 1.0, 2026-11-10. Reads results/c2/*.json; writes results/c2/decision.json and
results/c2/summary_tables.md.

Configurations per model and context:
- reference configs need no quality test: dense bf16 (Qwen and Granite release dtype) and
  dense fp32 (Qwen, upcast);
- B1-family configs (fp32-based int8) count only if they meet matched quality
  (PPL ratio <= 1.01 and top-1 >= 0.98 vs dense fp32).
C* = the fastest eligible config (lowest steady p50 step time).

Rule 1: time share upper bound s_up = min(1, s_hooked * (1 + o)) >= 0.5 at >= 1 context, for
each family. Rule 2: derived byte share >= 0.5, same condition. Rule 3: 'other' is reported,
never a processor target. Rule 4: B2 (typical) applies only if faster than plain greedy with
identical tokens. Rule 5: no eligible class -> charter change.
The 'all weights' aggregate (attn_proj + mlp + lm_head) is EXPLORATORY: it is not a
pre-registered class and does not enter rules 1-5.
"""
from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).resolve().parent.parent / "results" / "c2"
CLASSES = ["attn_core", "attn_proj", "mlp", "lm_head", "other"]
BYTE_KEY = {"attn_core": "kv_share", "attn_proj": "attn_proj_share", "mlp": "mlp_share", "lm_head": "lm_head_share"}


def load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def configs(model):
    """Yield (T, config_name, entry, quality_ok, host) for one model."""
    files = {"qwen05": ["breakdown_qwen05_bf16.json", "breakdown_b1_qwen05_fp32.json", "breakdown_b1_qwen05_bf16.json"],
             "granite4micro": ["breakdown_granite4micro_bf16.json", "breakdown_b1_granite4micro_bf16.json"]}[model]
    for f in files:
        d = load(f)
        if d is None:
            continue
        host = d["meta"]["host"]
        dtype = d["meta"]["dtype"]
        for T, e in d["contexts"].items():
            for v, ve in e["variants"].items():
                name = f"{v}_{dtype}"
                if v == "dense":
                    ok, why = True, "reference precision"
                else:
                    qT = d.get("quality", {}).get(T, {})
                    q = qT.get(v)
                    ok = bool(q and q["matched_quality"])
                    if q:
                        why = f"PPL {q['ppl_ratio']:.4f}, top-1 {q['top1_agree']:.4f}"
                    elif v in qT.get("skipped_slower_than_dense", []):
                        why = "not evaluated: slower than dense (cannot be C*)"
                    else:
                        why = "no quality data"
                yield int(T), name, ve, ok, why, host, f


def main():
    out = {"rule": "charter §5 + A1", "models": {}, "eligible": {}}
    lines = ["# C2 decision tables (generated by tests/c2_analyze.py)", ""]
    for model in ("qwen05", "granite4micro"):
        rows = list(configs(model))
        if not rows:
            continue
        hosts = {(r[5].get("cpu_model"), r[5].get("kernel")) for r in rows}
        per_T = {}
        for T, name, ve, ok, why, host, f in rows:
            per_T.setdefault(T, []).append((name, ve, ok, why, f))
        mres = {"hosts": sorted(map(str, hosts)), "contexts": {}}
        lines += [f"## {model}", "", f"Hosts: {sorted(map(str, hosts))}", "",
                  "| T | config | step ms p50 | tok/s | hook ovh | quality | " + " | ".join(f"s_up {c}" for c in CLASSES) + " | KV byte share | eff. GB/s |",
                  "|---:|---|---:|---:|---:|---|" + "---:|" * len(CLASSES) + "---:|---:|"]
        for T in sorted(per_T):
            cands = []
            for name, ve, ok, why, f in per_T[T]:
                o = ve["hook_overhead_frac"]
                s = ve["time_share_median"]
                s_up = {c: min(1.0, s[c] * (1 + max(o, 0.0))) for c in CLASSES}
                b = ve["bytes_derived"]
                byte = {c: b[BYTE_KEY[c]] for c in BYTE_KEY}
                w_agg = s["attn_proj"] + s["mlp"] + s["lm_head"]
                rec = {"config": name, "file": f, "step_s_p50": ve["steady_step_s_p50"], "tokens_per_s": ve["tokens_per_s"],
                       "hook_overhead": o, "quality_ok": ok, "quality": why, "s_hooked": s, "s_up": s_up, "byte_share": byte,
                       "effective_gbps": ve["effective_gbps_derived"],
                       "exploratory_all_weights_time_share_up": min(1.0, w_agg * (1 + max(o, 0.0))),
                       "exploratory_all_weights_byte_share": 1.0 - b["kv_share"]}
                cands.append(rec)
                lines.append(f"| {T} | {name} | {ve['steady_step_s_p50']*1e3:.2f} | {ve['tokens_per_s']:.2f} | {o:.3f} | {'ok' if ok else 'FAIL'} ({why}) | "
                             + " | ".join(f"{s_up[c]:.3f}" for c in CLASSES) + f" | {b['kv_share']:.3f} | {ve['effective_gbps_derived']:.1f} |")
            ok_c = [c for c in cands if c["quality_ok"]]
            cstar = min(ok_c, key=lambda c: c["step_s_p50"]) if ok_c else None
            mres["contexts"][str(T)] = {"candidates": cands, "C_star": cstar["config"] if cstar else None,
                                        "C_star_s_up": cstar["s_up"] if cstar else None,
                                        "C_star_byte_share": cstar["byte_share"] if cstar else None,
                                        "C_star_exploratory_all_weights": (cstar["exploratory_all_weights_time_share_up"], cstar["exploratory_all_weights_byte_share"]) if cstar else None}
        lines += ["", "C* per context: " + ", ".join(f"{T}: {mres['contexts'][str(T)]['C_star']}" for T in sorted(per_T)), ""]
        out["models"][model] = mres
    # rules 1/2 across families
    fams = list(out["models"])
    for c in CLASSES:
        t_ok = {m: any((ctx["C_star_s_up"] or {}).get(c, 0) >= 0.5 for ctx in out["models"][m]["contexts"].values()) for m in fams}
        b_ok = {m: any((ctx["C_star_byte_share"] or {}).get(c, 0) >= 0.5 for ctx in out["models"][m]["contexts"].values()) for m in fams} if c in BYTE_KEY else {m: None for m in fams}
        out["eligible"][c] = {"time_eligible_per_family": t_ok, "time_eligible": len(fams) == 2 and all(t_ok.values()),
                              "byte_eligible_per_family": b_ok, "byte_eligible": c in BYTE_KEY and len(fams) == 2 and all(b_ok.values()),
                              "processor_target": c != "other"}
    b2 = {}
    for m, f in (("qwen05", "b2_prompt_lookup_qwen05_bf16_T8192.json"), ("granite4micro", "b2_prompt_lookup_granite4micro_bf16_T8192.json")):
        d = load(f)
        if d is None:
            continue
        b2[m] = {k: {"speedup": v.get("lookup_speedup"), "ci95": v.get("lookup_speedup_ci95"), "identical": v.get("lookup_tokens_identical_to_plain"),
                     "plain_consistent": v.get("plain_generate_consistent_with_verified_path"),
                     "errors": (v.get("plain", {}).get("errors", []) + v.get("lookup", {}).get("errors", []))} for k, v in d["kinds"].items()}
    out["B2"] = b2
    out["rule4_B2_raises_bar"] = {m: bool(v.get("typical", {}).get("speedup") and v["typical"]["speedup"] > 1 and v["typical"]["identical"]) for m, v in b2.items()}
    elig = [c for c, e in out["eligible"].items() if e["processor_target"] and (e["time_eligible"] or e["byte_eligible"])]
    out["eligible_processor_targets"] = elig
    out["conclusion"] = ("eligible: " + ", ".join(elig)) if elig else "no single-bottleneck target reaches 2x on this workload (rule 5): charter change required"
    lines += ["## Eligibility (rules 1-2, both families required)", "", "| class | time-eligible (per family) | byte-eligible (per family) | processor target |", "|---|---|---|---|"]
    for c, e in out["eligible"].items():
        lines.append(f"| {c} | {e['time_eligible']} {e['time_eligible_per_family']} | {e['byte_eligible']} {e['byte_eligible_per_family']} | {e['processor_target']} |")
    lines += ["", f"B2: {json.dumps(b2)}", "", f"Rule 4 (B2 raises bar): {out['rule4_B2_raises_bar']}", "", f"**Conclusion (pre-registered rule):** {out['conclusion']}", "",
              "Exploratory (NOT a pre-registered class): all-weights aggregate (attn_proj + mlp + lm_head) time share upper bound and byte share at C*:", ""]
    for m, mr in out["models"].items():
        lines.append(f"- {m}: " + ", ".join(f"{T}: time ≤ {v['C_star_exploratory_all_weights'][0]:.3f}, bytes {v['C_star_exploratory_all_weights'][1]:.3f}"
                                           for T, v in sorted(mr["contexts"].items(), key=lambda x: int(x[0])) if v["C_star_exploratory_all_weights"]))
    (R / "decision.json").write_text(json.dumps(out, indent=1) + "\n")
    (R / "summary_tables.md").write_text("\n".join(lines) + "\n")
    print(out["conclusion"])


if __name__ == "__main__":
    main()
