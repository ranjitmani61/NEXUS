#!/usr/bin/env python3
"""Builds the self-contained Kaggle kernel script for a C3 run. Version 1.0, 2026-11-10.

The generated script (one file, as Kaggle script kernels require):
1. records the environment (nvidia-smi, docker image digest; allowlisted variables only);
2. pip-installs transformers==4.57.1 (the version every earlier NEXUS result used) and
   bitsandbytes (latest; its version is recorded);
3. precondition P1: SHA-256 of every model file listed in results/g5r/provenance_*.json, and
   of the four books, must match the attached Kaggle inputs; a mismatching model is not run;
4. runs tests/c3_gpu_breakdown.py (embedded as base64; its SHA-256 is recorded and re-checked
   after decoding) per model as a subprocess, each with a time budget, writing JSON and logs
   to /kaggle/working.

  python tests/c3_build_kernel.py --plan smoke|main --output <kernel.py>
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOOKS = ["860.txt", "2544.txt", "3247.txt", "3340.txt"]

PLANS = {
    # smoke: every code path on the GPU at tiny sizes. Outputs are NOT results.
    "smoke": {"label": "SMOKE: not a result", "hash_max_bytes": 100_000_000, "runs": [
        {"model": "qwen05", "tag": "qwen2.5", "budget": 300,
         "args": ["--contexts", "512", "1024", "--formats", "fp16", "nf4", "int8", "--steps", "4", "--reps", "1",
                  "--quality-T", "512", "--quality-steps", "8", "--consistency-T", "512"]},
        {"model": "granite4micro", "tag": "granite", "budget": 420,
         "args": ["--contexts", "512", "--formats", "fp16", "nf4", "int8", "--steps", "4", "--reps", "1",
                  "--quality-T", "512", "--quality-steps", "8", "--consistency-T", "512", "--ref-device-map", "auto"]}]},
    # smoke2 (Amendment A1): Granite only, to verify fixes C3-D2/C3-D3 on the GPU. NOT a result.
    "smoke2": {"label": "SMOKE: not a result", "hash_max_bytes": 100_000_000, "runs": [
        {"model": "granite4micro", "tag": "granite", "budget": 420,
         "args": ["--contexts", "512", "--formats", "fp16", "nf4", "int8", "--steps", "4", "--reps", "1",
                  "--quality-T", "512", "--quality-steps", "8", "--consistency-T", "512", "--ref-device-map", "auto"]}]},
    # main: the pre-registered C3 measurement (charter §4).
    "main": {"label": "result", "hash_max_bytes": None, "runs": [
        {"model": "qwen05", "tag": "qwen2.5", "budget": 1000,
         "args": ["--contexts", "4096", "8192", "16384", "32000", "--formats", "fp16", "nf4", "int8", "--steps", "16", "--reps", "5",
                  "--quality-T", "4096", "--quality-steps", "32", "--consistency-T", "4096"]},
        {"model": "granite4micro", "tag": "granite", "budget": 1500,
         "args": ["--contexts", "4096", "8192", "16384", "--formats", "fp16", "nf4", "int8", "--steps", "16", "--reps", "5",
                  "--quality-T", "4096", "--quality-steps", "32", "--consistency-T", "4096", "--ref-device-map", "auto"]}]},
}

RUNNER = r'''#!/usr/bin/env python3
# NEXUS C3 Kaggle kernel, generated by tests/c3_build_kernel.py (plan: __PLAN__).
# Charter: specs/C3_G0_gpu_decode_bottleneck_charter.md. Embedded tests/c3_gpu_breakdown.py sha256: __SHA__
import base64, hashlib, json, os, subprocess, sys, time
from pathlib import Path
# Test-only overrides (never set on Kaggle; recorded in the run record when set)
ROOTD = os.environ.get("NEXUS_C3_ROOT", "/kaggle")
OVR = {k: os.environ[k] for k in ("NEXUS_C3_ROOT", "NEXUS_C3_SKIP_PIP", "NEXUS_C3_EXTRA_ARGS") if k in os.environ}
W = Path(ROOTD) / "working"; W.mkdir(parents=True, exist_ok=True)
PLAN = json.loads(base64.b64decode("__PLAN_B64__").decode())
EXPECTED = json.loads(base64.b64decode("__EXP_B64__").decode())
SRC = base64.b64decode("__SRC_B64__")
REC = {"plan": "__PLAN__", "label": PLAN["label"], "script_sha256": "__SHA__", "start_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
REC["script_sha256_check"] = hashlib.sha256(SRC).hexdigest() == "__SHA__"
REC["test_overrides"] = OVR
def save(): (W / "c3_run_record.json").write_text(json.dumps(REC, indent=1, default=str) + "\n")
def sh(c, t=600):
    try:
        r = subprocess.run(c, shell=True, capture_output=True, text=True, timeout=t)
        return {"cmd": c, "rc": r.returncode, "out": r.stdout[-3000:], "err": r.stderr[-3000:]}
    except Exception as e:
        return {"cmd": c, "error": repr(e)}
REC["env"] = {k: os.environ.get(k) for k in ("KAGGLE_DOCKER_IMAGE", "KAGGLE_KERNEL_RUN_TYPE", "CUDA_VERSION") if os.environ.get(k)}
REC["nvidia_smi"] = sh("nvidia-smi --query-gpu=index,name,driver_version,memory.total,clocks.max.sm,power.limit --format=csv")
save()
t0 = time.time()
REC["pip"] = {"skipped": "test override"} if OVR.get("NEXUS_C3_SKIP_PIP") else sh(f"{sys.executable} -m pip install --no-input transformers==4.57.1 bitsandbytes", 900)
REC["pip"]["seconds"] = time.time() - t0
REC["versions"] = sh(f"{sys.executable} -c \"import torch, transformers; print(torch.__version__, torch.version.cuda, transformers.__version__); import bitsandbytes; print('bnb', bitsandbytes.__version__)\"")
save()
found = {}  # file name -> paths (names only; nothing is hashed here)
for root, dirs, files in os.walk(os.path.join(ROOTD, "input"), followlinks=True):
    for f in files:
        found.setdefault(f, []).append(os.path.join(root, f))
def sha(p):
    s = hashlib.sha256()
    with open(p, "rb") as fh:
        for ch in iter(lambda: fh.read(1 << 22), b""):
            s.update(ch)
    return s.hexdigest()
P1, model_dirs = {}, {}
t0 = time.time()
for run in PLAN["runs"]:
    key, tag = run["model"], run["tag"]
    res, mdir = {}, None
    for rel, want in EXPECTED[key].items():
        ps = [p for p in found.get(rel.split("/")[-1], []) if tag in p.lower()]
        if len(ps) != 1:
            res[rel] = {"ok": False, "why": f"{len(ps)} candidate paths", "paths": ps[:4]}
            continue
        lim = PLAN.get("hash_max_bytes")
        if lim is not None and os.path.getsize(ps[0]) > lim:  # smoke only: large files located, not hashed
            res[rel] = {"ok": True, "not_hashed_smoke_only": True, "bytes": os.path.getsize(ps[0]), "path": ps[0]}
        else:
            got = sha(ps[0])
            res[rel] = {"ok": got == want, "sha256": got, "path": ps[0]}
        if rel == "config.json":
            mdir = os.path.dirname(ps[0])
    P1[key] = {"files": res, "pass": bool(res) and all(v["ok"] for v in res.values()) and mdir is not None, "dir": mdir}
    model_dirs[key] = mdir
bres, book_paths = {}, []
for b, want in EXPECTED["pg19"].items():
    ps = found.get(b, [])
    ok = [p for p in ps if sha(p) == want]
    bres[b] = {"ok": bool(ok), "paths": ps[:4]}
    if ok:
        book_paths.append(ok[0])
P1["pg19"] = {"files": bres, "pass": all(v["ok"] for v in bres.values())}
REC["P1"] = P1; REC["P1_seconds"] = time.time() - t0; REC["inputs_file_names"] = len(found)
save()
(W / "c3_gpu_breakdown.py").write_bytes(SRC)
REC["runs"] = {}
for run in PLAN["runs"]:
    key = run["model"]
    if not REC["script_sha256_check"]:
        REC["runs"][key] = {"skipped": "embedded script hash mismatch"}; save(); continue
    if not (P1[key]["pass"] and P1["pg19"]["pass"]):
        REC["runs"][key] = {"skipped": "P1 failed: model or books do not match the provenance manifests"}; save(); continue
    outp = W / ("c3_" + ("smoke" if PLAN["label"].startswith("SMOKE") else "main") + f"_{key}.json")
    cmd = [sys.executable, str(W / "c3_gpu_breakdown.py"), "--model-dir", model_dirs[key], "--model-name", key,
           "--books", *book_paths, "--label", PLAN["label"], "--budget-s", str(run["budget"]), "--output", str(outp)] + run["args"] + OVR.get("NEXUS_C3_EXTRA_ARGS", "").split()
    t0 = time.time()
    with open(W / f"log_{key}.txt", "w") as lf:
        try:
            rc = subprocess.run(cmd, stdout=lf, stderr=subprocess.STDOUT, timeout=run["budget"] + 300).returncode
        except subprocess.TimeoutExpired:
            rc = "timeout"
    REC["runs"][key] = {"rc": rc, "seconds": time.time() - t0, "output": outp.name, "cmd": cmd}
    save()
REC["end_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
save()
print(json.dumps({"runs": REC["runs"], "end_utc": REC["end_utc"]}, indent=1, default=str))
'''


def expected():
    out = {}
    for key, f in (("qwen05", "provenance_qwen2.5-0.5b.json"), ("granite4micro", "provenance_granite-4.0-micro-base.json")):
        d = json.loads((ROOT / "results" / "g5r" / f).read_text())
        # files needed to load and run; .gitattributes/LICENSE/README are not needed
        out[key] = {e["path"]: e["sha256"] for e in d["files"] if e["path"].split("/")[-1] not in (".gitattributes", "LICENSE", "README.md")}
        assert "config.json" in out[key], key
    d = json.loads((ROOT / "results" / "g5r" / "provenance_pg19_selected.json").read_text())
    out["pg19"] = {e["path"].split("/")[-1]: e["sha256"] for e in d["files"] if e["path"].split("/")[-1] in BOOKS}
    assert sorted(out["pg19"]) == sorted(BOOKS), out["pg19"]
    return out


def build(plan: str) -> tuple[str, str]:
    src = (ROOT / "tests" / "c3_gpu_breakdown.py").read_bytes()
    sha = hashlib.sha256(src).hexdigest()
    b64 = lambda b: base64.b64encode(b).decode()  # noqa: E731
    body = (RUNNER.replace("__PLAN_B64__", b64(json.dumps(PLANS[plan]).encode()))
            .replace("__EXP_B64__", b64(json.dumps(expected()).encode()))
            .replace("__SRC_B64__", b64(src)).replace("__PLAN__", plan).replace("__SHA__", sha))
    return body, sha


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", choices=sorted(PLANS), required=True); ap.add_argument("--output", type=Path, required=True)
    a = ap.parse_args()
    body, sha = build(a.plan)
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text(body)
    print(json.dumps({"plan": a.plan, "script_sha256": sha, "kernel_bytes": len(body), "output": str(a.output)}))


if __name__ == "__main__":
    main()
